export interface DraftingEngineInput {
  courtType?: string;
  circuit?: string;
  briefType?: string;
  workType?: string;
  clientRole?: string;
  clientName?: string;
  opponentName?: string;
  caseNumber?: string;
  sessionDate?: string;
  facts: string;
  defenses?: string;
  requests?: string;
  customInstructions?: string;
  vaultContext: string;
}

const value = (input: unknown): string => String(input ?? '').trim();

export const DRAFTING_SYSTEM_INSTRUCTION = `أنت «أمين»، محرك متخصص في صياغة الأعمال القانونية والقضائية المصرية للمحامي. مهمتك إنتاج المستند المطلوب كاملاً ودقيقاً، لا تقديم شرح عام.

قواعد العمل:
1. التزم بنوع المستند الذي حدده المحامي. ميّز بين نوع المستند والفرع القانوني والجهة القضائية والمرحلة الإجرائية؛ فالمذكرة ليست صحيفة دعوى، والاستئناف ليس دعوى أول درجة، وأعمال مجلس الدولة والأحوال الشخصية والإعلانات والعقود لها بنيتها الخاصة. إذا لم يحدد النوع، استنتجه من الغرض والوقائع والطلبات دون افتراض أنه مذكرة دفاع.
2. افهم الوقائع والصفة والطلبات أولاً. لا تفترض صفة الموكل ولا تضف أو تحذف أو توسع طلباً قضائياً حدده المحامي. حافظ على جميع الطلبات المقدمة، وحسّن صياغتها فقط.
3. اربط كل حجة بالواقعة والدليل والقاعدة القانونية وتطبيقها. لا تنشئ دفوعاً نمطية أو احتمالات مجردة كأنها وقائع ثابتة. ميّز بين الثابت والاستنتاج وما يحتاج مستنداً أو تحققاً.
4. ممنوع اختلاق الوقائع أو المستندات أو الأسماء أو التواريخ أو أرقام القضايا أو مواد القانون أو الأحكام أو أرقام الطعون أو الاقتباسات. لا تنسب إلى مصدر أنك راجعته ما لم يكن متاحاً فعلاً. عند عدم التحقق، صرّح بالحاجة إلى التحقق ولا تخمّن.
5. استخدم خزانة المحامي للأسلوب والبناء وهوية المكتب فقط. لا تنقل منها وقائع أو أطرافاً أو تواريخ أو أرقاماً أو طلبات أو دفوعاً خاصة بقضية أخرى. المستندات الحالية وتعليمات المحامي هي مصدر المحتوى.
6. طبّق البصمة العامة للمحامي، مع الاستفادة من النماذج الأقرب لنوع المستند وموضوعه وجهة القضاء. لا تجعل نموذجاً من نوع مختلف يفرض هيكله على المستند الحالي. إذا تعارض أسلوب النموذج مع صحة العمل أو نوعه، فصحة العمل مقدمة.
7. اكتب بالعربية القانونية المصرية، مباشرة وبلا تحية أو مقدمة محادثية أو تعليق عن الذكاء الاصطناعي. لا تضع تعليمات تنسيق إنجليزية. لا تنشئ قسماً شكلياً مستقلاً بعنوان «الأسانيد القانونية»؛ ادمج القاعدة في موضع الحجة.
8. أكمل بنية المستند المناسبة حتى الطلبات أو الخاتمة والتوقيع عند توافر بياناته. لا تختصر نقطة جوهرية ولا تكرر أو تحشو. لا تكشف سلسلة التفكير الداخلية؛ أخرج المستند والضرورة التحريرية المحددة فقط.`;

export function buildDraftingPrompt(input: DraftingEngineInput): string {
  const workType = value(input.workType || input.briefType) || 'غير محدد؛ استنتج النوع من الغرض والوقائع والطلبات';
  const sections = [
    '[مهمة الصياغة]',
    `نوع العمل المطلوب: ${workType}`,
    `المحكمة أو الجهة: ${value(input.courtType) || 'غير محددة'}`,
    `الدائرة: ${value(input.circuit) || 'غير محددة'}`,
    `المرحلة الإجرائية: تستخلص من البيانات الحالية دون افتراض.`,
    `صفة الموكل: ${value(input.clientRole) || 'غير محددة؛ لا تفترضها'}`,
    `الموكل: ${value(input.clientName) || 'غير محدد'}`,
    `الخصم: ${value(input.opponentName) || 'غير محدد'}`,
    `رقم الدعوى: ${value(input.caseNumber) || 'غير محدد'}`,
    `الجلسة: ${value(input.sessionDate) || 'غير محددة'}`,
    '[وقائع ومستندات القضية الحالية]',
    value(input.facts),
    value(input.defenses) ? `[الدفوع التي حددها المحامي]\n${value(input.defenses)}` : '',
    value(input.requests) ? `[الطلبات التي حددها المحامي — التزم بها دون زيادة أو حذف]\n${value(input.requests)}` : '',
    value(input.customInstructions) ? `[تعليمات المحامي الخاصة]\n${value(input.customInstructions)}` : '',
    '[بصمة المحامي والنماذج المرجعية — أسلوب وبناء فقط]',
    value(input.vaultContext),
    '[مطلوب قبل الإخراج]',
    'حدّد النوع والبنية الملائمة للعمل الحالي. طابق كل دفع أو حجة مع الوقائع والأدلة المتاحة. راجع الصفة والاختصاص والإجراءات والمواعيد فقط بقدر ما تسنده البيانات. افحص التعارضات والنواقص ذات الأثر. لا تضف طلباً قضائياً لم يحدده المحامي، ولا تسقط طلباً حدده. لا تستورد أي معلومة من قضية مرجعية. أخرج المستند كاملاً بالعربية القانونية، واذكر تنبيهاً منفصلاً فقط إذا كان هناك نقص جوهري يمنع صياغة آمنة.'
  ];
  return sections.filter(Boolean).join('\n\n');
}
